"""行业（板块）静态映射表

当前行情数据源（腾讯/东财直连、westock、tdx）均未返回行业字段，
因此这里维护一份「股票代码 → 行业」的静态映射，覆盖默认蓝筹池
（config.DEFAULT_UNIVERSE）的全部标的，便于选股阶段做行业分散约束。

设计要点：
  - industry_of(code) 在映射缺失时回退 "其他"，保证任何代码都能归类，
    不会因未知行业而破坏选股流程。
  - 行业分类粒度适中：金融细分为 银行 / 保险 / 券商，新能源/电子/食品饮料
    等按主题聚合，使约束既能分散风险又不过度碎片化。
  - 后续若接入带行业字段的数据源（如 a-stock-data 的 F10/板块接口），
    可在 provider 层把行业写入 quote["sector"]，screener 会优先采用，
    本表自动退化为兜底。

扩展方式：直接往 SECTOR_MAP 增补 code -> 行业 即可。
"""
from __future__ import annotations

# 行业分类映射（申万一级/主题近似）。key 为 6 位 A 股代码字符串。
SECTOR_MAP: dict[str, str] = {
    # 食品饮料
    "600519": "食品饮料", "000858": "食品饮料", "600887": "食品饮料", "603288": "食品饮料",
    # 银行
    "600036": "银行", "601166": "银行", "000001": "银行", "601398": "银行", "600000": "银行",
    # 保险
    "601318": "保险", "601628": "保险",
    # 券商
    "600030": "券商",
    # 家电
    "000333": "家电", "000651": "家电",
    # 医药
    "600276": "医药",
    # 新能源（电池 / 汽车 / 光伏）
    "300750": "新能源", "002594": "新能源", "601012": "新能源",
    # 公用事业（电力）
    "600900": "公用事业",
    # 电子（面板 / 安防 / 消费电子）
    "000725": "电子", "002415": "电子", "002475": "电子",
    # 旅游零售
    "601888": "旅游零售",
    # 建材
    "600585": "建材",
    # 交运（机场）
    "600009": "交运",
    # 化工
    "600309": "化工",
    # 地产
    "000002": "地产",
    # 汽车（传统）
    "600104": "汽车",
    # 能源（石油）
    "601857": "能源", "600028": "能源",
}

# 未知代码的兜底行业名
_UNKNOWN_SECTOR = "其他"


def industry_of(code: str) -> str:
    """返回股票代码对应的行业；未知代码回退 '其他'。"""
    return SECTOR_MAP.get(str(code), _UNKNOWN_SECTOR)


def known_sectors() -> list[str]:
    """返回当前映射涵盖的所有行业（去重）。"""
    return sorted(set(SECTOR_MAP.values()))
